#!/usr/bin/env node

import { access, constants as FS_Constants, writeFile } from "fs/promises";
import { resolve } from "path";
import dedent from "dedent";
import { format } from "oxfmt";
import { shikiEngines, shikiGrammarLanguages, shikiGrammarThemes } from "../src/defs.ts";

const oxfmt = async (fileName: string, source: string) => {
  const { code, errors } = await format(fileName, source);

  if (errors?.length) {
    errors.forEach(({ message }) => console.error(message));

    return source;
  }

  return code;
};

const genBundleLanguageType = () => {
  return dedent`
    /** full grammar languages */
    export type _ShikiGrammarLanguage = ${shikiGrammarLanguages.map((lang) => `"${lang}"`).join(" | ")};
  `;
};

const genBundleThemeType = () => {
  return dedent`
    /** full grammar themes */
    export type _ShikiGrammarTheme = ${shikiGrammarThemes.map((theme) => `"${theme}"`).join(" | ")};
  `;
};

const genEngineType = () => {
  return dedent`
    export type _ShikiBundleEngine = ${shikiEngines.map((engine) => `"${engine}"`).join(" | ")};
  `;
};

const typingPath = resolve("src/typing.ts");

const genTypes = async () => {
  const types = dedent.withOptions({ alignValues: true })`
    /* Auto-generated by scripts/gen-types.ts. Do not edit manually. */

    export type EmptyRecord = Record<never, any>;

    export type ExtractRecord<T extends Record<any, any>> = {
      keys: keyof T;
      values: T[keyof T];
    };

    export type ReadonlyFields<T extends Record<any, any>> = {
      [K in keyof T as T[K] extends any[] ? never : T[K] extends ReadonlyArray<any> ? K : never]: T[K];
    };

    ${genBundleLanguageType()}

    ${genBundleThemeType()}

    ${genEngineType()}
  `;

  await access(typingPath, FS_Constants.F_OK | FS_Constants.W_OK);

  await writeFile(typingPath, await oxfmt("typing.ts", types), { encoding: "utf-8" });
};

genTypes();
