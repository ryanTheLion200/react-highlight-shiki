import type {
  _ShikiBundleEngine,
  _ShikiGrammarLanguage,
  _ShikiGrammarTheme,
  PickOptional,
} from "./typing";
import {
  engineModule,
  ensureShikiAliasLanguageMapping,
  ensureShikiBundledLanguageMapping,
  ensureShikiEngine,
  ensureShikiGrammarLanguages,
  ensureShikiGrammarThemes,
  shikiSpecialLanguageAliasMapping,
  shikiSpecialLanguages,
  shikiSpecialThemes,
  shorthandFunctions,
} from "./defs";
import { ShikiBundleCodeGenerator } from "./generator/code-generator";
import { genObjectLiteral, genStringLiteralType, TypeFormatHelpers } from "./helper";

export interface BundleOptions {
  /**
   * The header to add to the generated code.
   *
   * @default '/* Auto-generated by shiki-bundle-codegen *\/'
   */
  header?: string;

  /**
   * The grammar languages to bundle.
   */
  langs: _ShikiGrammarLanguage[];

  /**
   * The grammar themes to bundle.
   */
  themes: _ShikiGrammarTheme[];

  /**
   * The engine to use for syntax highlighting.
   */
  engine: _ShikiBundleEngine;

  /**
   * Use precompiled grammars.
   * Only available when `engine` is set to `javascript` or `javascript-raw`.
   *
   * @default false
   */
  precompiled?: boolean;

  /**
   * Whether to generate TypeScript code.
   *
   * @default true
   */
  typescript?: boolean;

  /**
   * Generate shorthands for the highlighter.
   *
   * @default true
   */
  shorthands?: boolean;
}

const defaultOptions = {
  header: "/* Auto-generated by shiki-bundle-codegen */",
  precompiled: false,
  typescript: true,
  shorthands: true,
} satisfies Required<PickOptional<BundleOptions>>;

export const shikiBundleCodegen = ({
  header = defaultOptions.header,
  langs,
  themes,
  engine,
  precompiled = defaultOptions.precompiled,
  typescript = defaultOptions.typescript,
  shorthands = defaultOptions.shorthands,
}: BundleOptions) => {
  const gen = new ShikiBundleCodeGenerator({
    langs: ensureShikiGrammarLanguages(langs) as BundleOptions["langs"],
    themes: ensureShikiGrammarThemes(themes) as BundleOptions["themes"],
    engine: ensureShikiEngine(engine, { precompiled }),
    precompiled,
    typescript,
    shorthands,
  });

  const bundledLanguageMapping = ensureShikiBundledLanguageMapping(langs);
  const aliasMapping = ensureShikiAliasLanguageMapping(langs);

  const objectLiteral = genObjectLiteral({ typescript });
  const { typeAnnotation, generic } = new TypeFormatHelpers({ typescript });

  const EOL = gen.EOL;

  // #region imports
  gen.imports([
    typescript && {
      typeOnly: true,
      named: [
        "DynamicImportLanguageRegistration",
        "DynamicImportThemeRegistration",
        "HighlighterGeneric",
      ],
      from: "@shikijs/types",
    },
    ({ shorthands }) => ({
      typeOnly: false,
      named: ["createBundledHighlighter", shorthands && "createSingletonShorthands"],
      from: "@shikijs/core",
    }),
    ({ engine }) => `{ ${engineModule[engine].factory.name} } from "${engineModule[engine].from}"`,
  ]);
  // #endregion

  // #region types
  if (typescript) {
    // type: langs
    gen
      .line(`type BundledLanguage = ${genStringLiteralType(Object.keys(bundledLanguageMapping))}`)
      .newLine()
      .line(`type ShikiBaseLanguage = ShikiGrammarLanguage | ShikiSpecialLanguage`)
      .line(({ langs }) => `type ShikiGrammarLanguage = ${genStringLiteralType(langs)}`)
      .line(`type ShikiSpecialLanguage = ${genStringLiteralType(shikiSpecialLanguages)}`)
      .newLine()
      .line(`type ShikiLanguageAlias = ShikiGrammarLanguageAlias | ShikiSpecialLanguageAlias`)
      .line(`type ShikiGrammarLanguageAlias = ${genStringLiteralType(Object.keys(aliasMapping))}`)
      .line(
        `type ShikiSpecialLanguageAlias = ${genStringLiteralType(Object.keys(shikiSpecialLanguageAliasMapping))}`,
      )
      .newLine();

    // type: themes
    gen
      .line(
        ({ themes }) => `type BundledTheme = ${themes.map((theme) => `"${theme}"`).join(" | ")}`,
      )
      .newLine()
      .line(`type ShikiBaseTheme = ShikiGrammarTheme | ShikiSpecialTheme`)
      .line(({ themes }) => `type ShikiGrammarTheme = ${genStringLiteralType(themes)}`)
      .line(`type ShikiSpecialTheme = ${genStringLiteralType(shikiSpecialThemes)}`)
      .newLine();

    // type: highlighter
    gen.line(`type Highlighter = HighlighterGeneric<BundledLanguage, BundledTheme>`).newLine();
  }
  // #endregion

  // #region bundle
  gen
    .line(
      ({ precompiled }) =>
        `const bundledLanuages = ${objectLiteral(
          bundledLanguageMapping,
          ({ value: grammarLanguage }) =>
            `() => import("@shikijs/${precompiled ? "langs-precompiled" : "langs"}/${grammarLanguage}")`,
        ).as("Record<BundledLanguage, DynamicImportLanguageRegistration>")}`,
    )
    .line(
      ({ langs }) =>
        `const shikiGrammarLanguages${typeAnnotation`ShikiGrammarLanguage[]`} = [${langs.map((lang) => `"${lang}"`).join(", ")}]`,
    )
    .line(
      `const shikiSpecialLanguages${typeAnnotation`ShikiSpecialLanguage[]`} = [${shikiSpecialLanguages.map((lang) => `"${lang}"`).join(", ")}]`,
    )
    .line(
      `const shikiBaseLanguages${typeAnnotation`ShikiBaseLanguage[]`} = [...shikiGrammarLanguages, ...shikiSpecialLanguages]`,
    )
    .line(
      `const aliasLanguageMapping = ${objectLiteral(
        {
          ...aliasMapping,
          ...shikiSpecialLanguageAliasMapping,
        } as Record<string, string>,
        ({ value: baseLanguage }) => `"${baseLanguage}"`,
      ).as("Record<ShikiLanguageAlias, ShikiBaseLanguage>")}`,
    )
    .newLine()
    .line(
      ({ themes }) =>
        `const bundledThemes = ${objectLiteral(
          Object.fromEntries(themes.map((theme) => [theme, theme])),
          ({ value: theme }) => `() => import("@shikijs/themes/${theme}")`,
        ).as("Record<BundledTheme, DynamicImportThemeRegistration>")}`,
    )
    .line(
      ({ themes }) =>
        `const shikiGrammarThemes${typeAnnotation`ShikiGrammarTheme[]`} = [${themes.map((theme) => `"${theme}"`).join(", ")}]`,
    )
    .line(
      `const shikiSpecialThemes${typeAnnotation`ShikiSpecialTheme[]`} = [${shikiSpecialThemes.map((theme) => `"${theme}"`).join(", ")}]`,
    )
    .line(
      `const shikiBaseThemes${typeAnnotation`ShikiBaseTheme[]`} = [...shikiGrammarThemes, ...shikiSpecialThemes]`,
    )
    .newLine()
    .line(({ engine }) => {
      const targetEngine = engineModule[engine];

      const highlighterOptions = {
        langs: "bundledLanguages",
        themes: "bundledThemes",
        engine: `() => ${targetEngine.factory.name}(${"args" in targetEngine.factory ? targetEngine.factory.args.join(", ") : ""})`,
      };

      return `const createHighlighter = ${ShikiBundleCodeGenerator.PURE_COMMENT} createBundledHighlighter${generic`BundledLanguage, BundledTheme`}(${objectLiteral(highlighterOptions).literal})`;
    })
    .line(({ shorthands }) => shorthands && EOL)
    .line(
      ({ shorthands }) =>
        shorthands &&
        `const { ${shorthandFunctions.join(", ")} } = ${ShikiBundleCodeGenerator.PURE_COMMENT} createSingletonShorthands${generic`BundledLanguage, BundledTheme`}(createHighlighter)`,
    );
  // #endregion

  // #region exports
  gen
    .export(({ shorthands }) => {
      const named = ["bundledLanguages", "bundledThemes", "createHighlighter"];

      if (shorthands) {
        named.push(...shorthandFunctions);
      }

      named.push(
        // langs
        "shikiBaseLanguages",
        "shikiGrammarLanguages",
        "shikiSpecialLanguages",
        "aliasLanguageMapping",
        // themes
        "shikiBaseThemes",
        "shikiGrammarThemes",
        "shikiSpecialThemes",
      );

      return {
        typeOnly: false,
        named,
      };
    })
    .export(
      typescript && {
        typeOnly: true,
        named: [
          // langs
          "BundledLanguage",
          "ShikiBaseLanguage",
          "ShikiGrammarLanguage",
          "ShikiSpecialLanguage",
          "ShikiLanguageAlias",
          "ShikiGrammarLanguageAlias",
          "ShikiSpecialLanguageAlias",
          // themes
          "BundledTheme",
          "ShikiBaseTheme",
          "ShikiGrammarTheme",
          "ShikiSpecialTheme",
          // highlighter
          "Highlighter",
        ],
      },
    );
  // #endregion

  return [header, gen.code()].join(EOL);
};
